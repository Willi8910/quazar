/** An agent's logo in its colour; agents without one show their name instead. */
export function AgentIcon({
  agent,
  color,
  label,
  size = 12,
}: {
  agent: string;
  color?: string;
  label?: string;
  size?: number;
}) {
  const logo = AGENT_LOGOS[agent];
  if (!logo)
    return (
      <span className="agent-tag" style={{ color }}>
        {agent}
      </span>
    );
  return (
    <span className="agent-icon" title={label ?? agent} aria-label={label ?? agent} role="img">
      <svg viewBox="0 0 24 24" width={size} height={size} fill={color ?? "currentColor"}>
        <path d={logo} />
      </svg>
    </span>
  );
}

